create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default 'Member' check (char_length(display_name) between 1 and 60),
 status text not null default 'pending' check (status in ('pending','approved','rejected','suspended')),
 role text not null default 'member' check (role in ('member','admin')),
 created_at timestamptz not null default now()
);

create or replace function public.new_member_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 insert into public.profiles(id,display_name,status,role)
 values(new.id, left(coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'),''),split_part(new.email,'@',1),'Member'),60),'pending','member')
 on conflict (id) do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute function public.new_member_profile();

-- Backfill existing accounts, keeping access pending until approved.
insert into public.profiles(id,display_name)
select id,left(coalesce(nullif(trim(raw_user_meta_data->>'display_name'),''),split_part(email,'@',1),'Member'),60)
from auth.users on conflict(id) do nothing;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'admin' and status = 'approved');
$$;
create or replace function public.is_approved() returns boolean
language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.profiles where id = (select auth.uid()) and status = 'approved');
$$;
revoke all on function public.is_admin() from public;
revoke all on function public.is_approved() from public;
grant execute on function public.is_admin(), public.is_approved() to authenticated;

alter table public.profiles enable row level security;
drop policy if exists "Read own profile or admin list" on public.profiles;
drop policy if exists "Admins update member status" on public.profiles;
create policy "Read own profile or admin list" on public.profiles for select to authenticated
 using (id = (select auth.uid()) or (select public.is_admin()));
create policy "Admins update member status" on public.profiles for update to authenticated
 using ((select public.is_admin()) and role = 'member')
 with check ((select public.is_admin()) and role = 'member');
-- Members cannot insert or delete profiles or elevate their role. Admins can change member status only.
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update(status) on public.profiles to authenticated;

create table if not exists public.messages (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 display_name text not null default 'Member',
 body text not null check (char_length(body) between 1 and 5000),
 created_at timestamptz not null default now()
);
alter table public.messages enable row level security;
drop policy if exists "Authenticated members can read messages" on public.messages;
drop policy if exists "Members can insert their own messages" on public.messages;
drop policy if exists "Members can delete their own messages" on public.messages;
drop policy if exists "Approved members read messages" on public.messages;
drop policy if exists "Approved members send messages" on public.messages;
drop policy if exists "Approved members delete own messages" on public.messages;
create policy "Approved members read messages" on public.messages for select to authenticated using ((select public.is_approved()));
create policy "Approved members send messages" on public.messages for insert to authenticated with check ((select public.is_approved()) and user_id = (select auth.uid()));
create policy "Approved members delete own messages" on public.messages for delete to authenticated using ((select public.is_approved()) and user_id = (select auth.uid()));
revoke all on public.messages from anon,authenticated;
grant select,insert,delete on public.messages to authenticated;
grant usage,select on sequence public.messages_id_seq to authenticated;

do $$ begin
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='messages') then
 alter publication supabase_realtime add table public.messages;
 end if;
end $$;

