-- Private Members Chat: database setup
-- Run this entire file in Supabase Dashboard > SQL Editor > New query.

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Member',
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

-- Remove these named policies first so this script can safely be re-run.
drop policy if exists "Authenticated members can read messages" on public.messages;
drop policy if exists "Members can insert their own messages" on public.messages;
drop policy if exists "Members can delete their own messages" on public.messages;

create policy "Authenticated members can read messages"
on public.messages for select
to authenticated
using (true);

create policy "Members can insert their own messages"
on public.messages for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Members can delete their own messages"
on public.messages for delete
to authenticated
using (auth.uid() = user_id);

-- No UPDATE policy is created: members cannot edit messages through the API.
grant select, insert, delete on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- Add messages to the Supabase Realtime publication (safe to run more than once).
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end
$$;